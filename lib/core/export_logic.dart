import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:printing/printing.dart';
import 'package:excel/excel.dart';

class ExportLogic {
  
  // ==========================================
  // PDF EXPORT: EXECUTIVE SUMMARY
  // ==========================================
  static Future<void> generateExecutivePDF({
    required String month,
    required int growth,
    required double attendance,
    required List<String> missingUnits,
  }) async {
    final pdf = pw.Document();

    pdf.addPage(
      pw.Page(
        pageFormat: PdfPageFormat.a4,
        build: (pw.Context context) {
          return pw.Column(
            crossAxisAlignment: pw.CrossAxisAlignment.start,
            children: [
              pw.Header(level: 0, child: pw.Text("MONTHLY PERFORMANCE REPORT - $month")),
              pw.SizedBox(height: 20),
              pw.Text("Net Church Growth: $growth members"),
              pw.Text("Average Church Attendance: ${attendance.toStringAsFixed(1)}%"),
              pw.SizedBox(height: 20),
              pw.Text("Reporting Compliance Gaps:", style: pw.TextStyle(fontWeight: pw.FontWeight.bold)),
              pw.Bullet(text: "Total Units Missing: ${missingUnits.length}"),
              ...missingUnits.map((u) => pw.Text("- $u")),
              pw.SizedBox(height: 40),
              pw.Divider(),
              pw.Text("Generated by DRA Manager System", style: pw.TextStyle(fontSize: 10, color: PdfColors.grey)),
            ],
          );
        },
      ),
    );

    await Printing.layoutPdf(onLayout: (PdfPageFormat format) async => pdf.save());
  }

  // ==========================================
  // EXCEL EXPORT: RAW DATA DUMP (FIXED FOR EXCEL 4.0+)
  // ==========================================
  static void exportToExcel(List<dynamic> data, String fileName) {
    var excel = Excel.createExcel();
    Sheet sheetObject = excel['Sheet1'];

    // 1. Add Headers (Wrapped in TextCellValue)
    sheetObject.appendRow([
      TextCellValue("Name"),
      TextCellValue("Status"),
      TextCellValue("Date"),
      TextCellValue("Unit"),
    ]);

    // 2. Add Data Rows
    for (var row in data) {
      // Ensure we handle nulls safely with ?? "-"
      sheetObject.appendRow([
        TextCellValue((row['members']?['english_name'] ?? "-").toString()),
        TextCellValue((row['attendance_realtime'] ?? "-").toString()),
        TextCellValue((row['report_date'] ?? "-").toString()),
        TextCellValue((row['unit_name'] ?? "-").toString()),
      ]);
    }

    // Save the file
    excel.save(fileName: "$fileName.xlsx");
  }
}